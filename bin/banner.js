const HEIGHT = 7;
const WIDTH = 5;

function canColor() {
  return !!process.stdout.isTTY && !process.env.NO_COLOR &&
    (process.env.COLORTERM === 'truecolor' || process.env.COLORTERM === '24bit');
}

/**
 * 把 text 渲染成多行大号字符画。
 * @param {string} text
 * @param {{char?:string, gap?:number, color?:boolean, from?:number[], to?:number[]}} opts
 * @returns {string}
 */
function render(text, opts = {}) {
  const fill = String(opts.char || '#').slice(0, 1) || '#';
  const gap = Number.isFinite(opts.gap) ? Math.max(0, opts.gap) : 1;
  const words = String(text || '').toUpperCase().split('');
  const cols = words.map(c => FONT[c] || FONT[' ']);
  const lines = [];
  for (let y = 0; y < HEIGHT; y++) {
    let line = '';
    for (const glyph of cols) {
      line += (glyph[y] || '.....').padEnd(WIDTH, '.').replace(/#/g, fill).replace(/\./g, ' ');
      line += ' '.repeat(gap);
    }
    lines.push(line.replace(/\s+$/, ''));
  }
  const useColor = opts.color === true && canColor();
  if (!useColor) return lines.join('\n');
  const a = opts.from || [255, 82, 168];   // 品红，跟站里 --ink 呼应
  const b = opts.to   || [219, 194, 145];  // 金，跟 --Akivili 呼应
  return lines.map((line, i) => {
    const t = lines.length > 1 ? i / (lines.length - 1) : 0;
    const c = a.map((v, k) => Math.round(v + (b[k] - v) * t)).join(';');
    return `\x1b[38;2;${c}m${line}\x1b[0m`;
  }).join('\n');
}

/** 有没有不支持的字符（中文、emoji、∞ …） */
function hasUnsupported(text) {
  return String(text || '').toUpperCase().split('').some(c => !(c in FONT));
}

/**
 * 直接打印启动横幅。返回打印过的行数（供日志/测试用）。
 */
function print(opts = {}) {
  const title = String(opts.title || 'ASCII FULL');
  const subtitle = opts.subtitle ? String(opts.subtitle) : '';
  const color = opts.color !== false;
  if (opts.file) {
    const fs = require('fs');
    try { console.log(fs.readFileSync(opts.file, 'utf8').replace(/\s+$/, '')); }
    catch (e) { console.log(render(title, { ...opts, color })); }
  } else {
    console.log(render(title, { ...opts, color }));
    if (hasUnsupported(title)) {
      console.log('  (标题里有非点阵字符，已按空格处理；想用中文/∞ 请给 --logo-file)');
    }
  }
  if (subtitle) console.log('  ' + subtitle);
  console.log('');
  return HEIGHT + (subtitle ? 1 : 0) + 1;
}

